// Текст опису для помічника (зріз 4): одна нормалізація для детектора вказівок (rules.ts) і для межі даних (prompts/line.ts),
// щоб обидва бачили той самий текст (відгук викладача на WS10: межа вирізала лише точний ASCII-тег, а «＜/document＞» чи
// тег із zero-width space лишались). NFKC зводить повноширинні й стилізовані символи до звичайних, \p{Cf} прибирає
// невидимі (zero-width space, м'який перенос).
export function normalizeText(text: string): string {
  return text.normalize("NFKC").replace(/\p{Cf}/gu, "");
}

